CREATE OR REPLACE PACKAGE BODY PA_PRODUCTOS AS
  TYPE TR_PROD IS RECORD (
    PROD_ID PRODUCT.PRODUCT_ID%TYPE,
    DESCR PRODUCT.DESCRIPTION%TYPE,
    CANT NUMBER
  );

  TYPE TT_PROD IS TABLE OF TR_PROD INDEX BY BINARY_INTEGER;
  T_PROD TT_PROD;

  FUNCTION FU_PROD_ID (PI_DESCR PRODUCT.DESCRIPTION%TYPE)
  RETURN PRODUCT.PRODUCT_ID%TYPE IS
    IDX NUMBER;
    E_NO_ENC EXCEPTION;
  BEGIN
    IDX := T_PROD.FIRST;
    WHILE T_PROD(IDX).DESCR < PI_DESCR LOOP
      IDX := T_PROD.NEXT(IDX);
    END LOOP;

    IF T_PROD(IDX).DESCR = PI_DESCR THEN
      RETURN T_PROD(IDX).PROD_ID;
    ELSE
      RAISE E_NO_ENC;
    END IF;
  EXCEPTION
    WHEN E_NO_ENC THEN
      RAISE_APPLICATION_ERROR(-20001, 'No existe el producto');
    WHEN OTHERS THEN
      RAISE_APPLICATION_ERROR(-20003, 'Error al buscar el producto: ' || SQLERRM);
  END FU_PROD_ID;

  PROCEDURE PR_BAJA(PI_ID PRODUCT.PRODUCT_ID%TYPE) AS
    E_FK EXCEPTION;
  BEGIN
    DELETE FROM PRODUCT
    WHERE PRODUCT_ID = PI_ID;

    IF SQL%ROWCOUNT = 0 THEN
      DBMS_OUTPUT.PUT_LINE('El producto no existe');
    ELSE
      DBMS_OUTPUT.PUT_LINE('El producto se borro exitosamente');
    END IF;

  EXCEPTION
    WHEN E_FK THEN
      DBMS_OUTPUT.PUT_LINE('El producto tiene relaciones y no se puede borrar');
  END PR_BAJA;
--ONE-TIME ONLY
BEGIN
  SELECT P.PRODUCT_ID, DESCRIPTION, SUM(NVL(I.QUANTITY, 0))
    BULK COLLECT INTO T_PROD
    FROM PRODUCT P, ITEM I
    WHERE P.PRODUCT_ID = I.PRODUCT_ID (+) -- (+) indica right outer join
    GROUP BY P.PRODUCT_ID, DESCRIPTION;
END PA_PRODUCTOS;