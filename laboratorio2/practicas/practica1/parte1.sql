SELECT 
  E.LAST_NAME AS APELLIDO,
  E.FIRST_NAME AS NOMBRE,
  E.SALARY AS SALARIO,
  D.NAME
FROM EMPLOYEE E, DEPARTMENT D
WHERE E.DEPARTMENT_ID = D.DEPARTMENT_ID
  AND EXISTS (SELECT 1 FROM EMPLOYEE E1 WHERE E1.JOB_ID = E.JOB_ID AND E1.FIRST_NAME = 'JOHN' AND E1.LAST_NAME = 'SMITH')
ORDER BY SALARIO, APELLIDO;

