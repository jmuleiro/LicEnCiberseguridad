-- 30)
SELECT D.DEPARTMENT_ID, 
  D.NAME AS NOMBRE_DEPTO, 
  ROUND(AVG(E.SALARY)) AS PROMEDIO_SALARIOS
FROM DEPARTMENT D, EMPLOYEE E
WHERE E.DEPARTMENT_ID = D.DEPARTMENT_ID
GROUP BY D.DEPARTMENT_ID, NOMBRE_DEPTO
ORDER BY PROMEDIO_SALARIOS;

-- 31)
SELECT D.DEPARTMENT_ID, 
  D.NAME AS NOMBRE_DEPTO, 
  ROUND(AVG(E.SALARY)) AS PROMEDIO_SALARIOS
FROM DEPARTMENT D, EMPLOYEE E
WHERE E.DEPARTMENT_ID = D.DEPARTMENT_ID
GROUP BY D.DEPARTMENT_ID, NOMBRE_DEPTO
HAVING COUNT(E.EMPLOYEE_ID) > 3
ORDER BY PROMEDIO_SALARIOS;

-- 32) 
SELECT P.PRODUCT_ID, 
  SUM(I.QUANTITY) AS UNIDADES_PEDIDAS, 
  MAX(I.TOTAL) AS TOTAL_FACTURADO
FROM PRODUCT P, ITEM I
WHERE P.PRODUCT_ID = I.PRODUCT_ID
GROUP BY P.PRODUCT_ID;

-- 33)
SELECT 
  C.NAME,
  '+' || C.AREA_CODE || ' ' || C.PHONE_NUMBER AS TELEFONO,
  COUNT(S.ORDER_ID),
  MAX(S.ORDER_DATE)
FROM CUSTOMER C, SALES_ORDER S
WHERE C.CUSTOMER_ID = S.CUSTOMER_ID
GROUP BY C.NAME, TELEFONO;

-- 34)
SELECT L.LOCATION_ID, 
  L.REGIONAL_GROUP,
  COUNT(E.EMPLOYEE_ID) AS TOTAL_EMPLEADOS,
  SUM(E.SALARY) AS TOTAL_SALARIOS
FROM LOCATION L,
  DEPARTMENT D,
  EMPLOYEE E
WHERE L.LOCATION_ID = D.LOCATION_ID
  AND D.DEPARTMENT_ID = E.DEPARTMENT_ID
GROUP BY L.LOCATION_ID, L.REGIONAL_GROUP
ORDER BY TOTAL_EMPLEADOS;

-- 35)
SELECT E.FIRST_NAME || ' ' || E.LAST_NAME AS NOMBRE,
  D.NAME,
  E.SALARY,
  J.FUNCTION
FROM EMPLOYEE E, DEPARTMENT D, JOB J
WHERE E.DEPARTMENT_ID = D.DEPARTMENT_ID
  AND E.JOB_ID = J.JOB_ID
  AND E.SALARY > (
    SELECT E1.SALARY 
    FROM EMPLOYEE E1 
    WHERE E1.EMPLOYEE_ID = E.MANAGER_ID
  );
