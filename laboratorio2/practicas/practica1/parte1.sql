  E1.EMPLOYEE_ID AS EMPLOYEE_ID,
  E1.LAST_NAME || ', ' || E1.FIRST_NAME AS EMP_NAME,
  E2.EMPLOYEE_ID AS MANAGER_ID,
  E2.LAST_NAME || ', ' || E2.FIRST_NAME AS MNG_NAME
