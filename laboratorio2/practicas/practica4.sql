CREATE OR REPLACE PROCEDURE PR_ALTA_JOB (
  PI_JOB_FUNCTION JOB.FUNCTION%TYPE
) AS
  V_JOB_ID JOB.JOB_ID%TYPE;
BEGIN
  SELECT MAX(JOB_ID)
  INTO V_JOB_ID
  FROM JOB;
  
  V_JOB_ID := V_JOB_ID + 1;

  INSERT INTO JOB (JOB_ID, FUNCTION)
  VALUES (V_JOB_ID, UPPER(PI_JOB_FUNCTION));
EXCEPTION
  WHEN OTHERS THEN
    DBMS_OUTPUT.PUT_LINE('Error inesperado: ' || SQLERRM);
END PR_ALTA_JOB;

-- 2)
CREATE OR REPLACE PROCEDURE PR_UPDATE_JOB (
  PI_JOB_ID JOB.JOB_ID%TYPE,
  PI_JOB_FUNCTION JOB.FUNCTION%TYPE
) AS
  E_NOT_FOUND EXCEPTION;
BEGIN
  UPDATE JOB
  SET FUNCTION = PI_JOB_FUNCTION
  WHERE JOB_ID = PI_JOB_ID;

  IF SQL%ROWCOUNT = 0 THEN
    RAISE E_NOT_FOUND;
  END IF;
EXCEPTION
  WHEN E_NOT_FOUND THEN
    DBMS_OUTPUT.PUT_LINE('No se encontró el job con ID: ' || PI_JOB_ID);
  WHEN OTHERS THEN
    DBMS_OUTPUT.PUT_LINE('Error inesperado: ' || SQLERRM);
END;

