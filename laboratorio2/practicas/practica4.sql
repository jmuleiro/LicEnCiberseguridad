CREATE OR REPLACE FUNCTION FU_VALIDA_LOC (
  PI_LOCATION_ID LOCATION.LOCATION_ID%TYPE
) RETURN BOOLEAN AS
  V_LOC_ID LOCATION.LOCATION_ID%TYPE;
BEGIN
  SELECT LOCATION_ID
  INTO V_LOC_ID
  FROM LOCATION
  WHERE LOCATION_ID = PI_LOCATION_ID;

  RETURN TRUE;
EXCEPTION
  WHEN NO_DATA_FOUND THEN
    RETURN FALSE;
END;

