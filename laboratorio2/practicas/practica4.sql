CREATE OR REPLACE PROCEDURE PR_NEW_DEPT (
  PI_DEPARTMENT_ID IN DEPARTMENT.DEPARTMENT_ID%TYPE,
  PI_DEPARTMENT_NAME IN DEPARTMENT.NAME%TYPE,
  PI_LOCATION_ID IN DEPARTMENT.LOCATION_ID%TYPE
) AS
  E_LOCATION_NOT_FOUND EXCEPTION;
  E_DEPARTMENT_EXISTS EXCEPTION;
  PRAGMA EXCEPTION_INIT(E_DEPARTMENT_EXISTS, -00001);
BEGIN
  IF NOT FU_VALIDA_LOC(PI_LOCATION_ID) THEN
    RAISE E_LOCATION_NOT_FOUND;
  END IF;

  INSERT INTO DEPARTMENT (DEPARTMENT_ID, NAME, LOCATION_ID)
  VALUES (PI_DEPARTMENT_ID, PI_DEPARTMENT_NAME, PI_LOCATION_ID);
EXCEPTION
  WHEN E_LOCATION_NOT_FOUND THEN
    DBMS_OUTPUT.PUT_LINE('No existe la location ID: ' || PI_LOCATION_ID);
  WHEN E_DEPARTMENT_EXISTS THEN
    DBMS_OUTPUT.PUT_LINE('Ya existe un departamento con ID: ' || PI_DEPARTMENT_ID);
  WHEN OTHERS THEN
    DBMS_OUTPUT.PUT_LINE('Error inesperado: ' || SQLERRM);
END;

