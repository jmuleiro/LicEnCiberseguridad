CREATE OR REPLACE PROCEDURE PR_LISTA_EMP (
  PI_DEPARTMENT_ID DEPARTMENT.DEPARTMENT_ID%TYPE
) AS
  CURSOR C_EMPLEADOS IS 
    SELECT FIRST_NAME, LAST_NAME
    FROM EMPLOYEE
    WHERE DEPARTMENT_ID = PI_DEPARTMENT_ID
    ;
  V_CONT INTEGER := 0;
  V_CANT_EMPLEADOS INTEGER := 0;
  E_SIN_EMPLEADOS EXCEPTION;
  E_DEPTO_INEXISTENTE EXCEPTION;
BEGIN
  DECLARE
    V_DEPTO_ID DEPARTMENT.DEPARTMENT_ID%TYPE := PI_DEPARTMENT_ID;
  BEGIN
    SELECT DEPARTMENT_ID
    INTO V_DEPTO_ID
    FROM DEPARTMENT
    WHERE DEPARTMENT_ID = V_DEPTO_ID;
  EXCEPTION
    WHEN NO_DATA_FOUND THEN
      RAISE E_DEPTO_INEXISTENTE;
  END;
  
  SELECT COUNT(*)
  INTO V_CANT_EMPLEADOS
  FROM EMPLOYEE
  WHERE DEPARTMENT_ID = PI_DEPARTMENT_ID;

  IF V_CANT_EMPLEADOS = 0 THEN
    RAISE E_SIN_EMPLEADOS;
  END IF;

  FOR REC IN C_EMPLEADOS LOOP
    V_CONT := V_CONT + 1;
    DBMS_OUTPUT.PUT_LINE(REC.LAST_NAME || ', ' || REC.FIRST_NAME);
  END LOOP;
EXCEPTION
  WHEN E_SIN_EMPLEADOS THEN
    DBMS_OUTPUT.PUT_LINE('El departamento no tiene empleados');
  WHEN E_DEPTO_INEXISTENTE THEN
    DBMS_OUTPUT.PUT_LINE('El departamento no existe');
  WHEN OTHERS THEN
    DBMS_OUTPUT.PUT_LINE('Error inesperado: ' || SQLERRM);
END;

