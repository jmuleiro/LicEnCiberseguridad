DECLARE
  V_EMPLEADO EMPLOYEE.EMPLOYEE_ID%TYPE := &INGRESE_ID;
  TYPE TR_EMP IS RECORD (
    NOMBRE EMPLOYEE.FIRST_NAME%TYPE,
    APELLIDO EMPLOYEE.LAST_NAME%TYPE,
    SALARIO EMPLOYEE.SALARY%TYPE
  );
  R_EMP TR_EMP;
BEGIN
  SELECT FIRST_NAME, LAST_NAME, SALARY
  INTO R_EMP
  FROM EMPLOYEE
  WHERE EMPLOYEE_ID = V_EMPLEADO;
  DBMS_OUTPUT.PUT_LINE(R_EMP.NOMBRE || ', ' || R_EMP.APELLIDO || ' tiene un salario de ' || R_EMP.SALARIO || ' pesos.');
END;

