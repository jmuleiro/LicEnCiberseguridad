DECLARE
  V_ORDEN_ID SALES_ORDER.ORDER_ID%TYPE := &INGRESE_ORDER_ID;
  TYPE TR_ORDER IS RECORD (
    ORDER_ID SALES_ORDER.ORDER_ID%TYPE,
    ORDER_DATE SALES_ORDER.ORDER_DATE%TYPE,
    CUSTOMER_ID SALES_ORDER.CUSTOMER_ID%TYPE,
    SHIP_DATE SALES_ORDER.SHIP_DATE%TYPE,
    TOTAL SALES_ORDER.TOTAL%TYPE
  );
  R_ORDER TR_ORDER;
BEGIN
  SELECT ORDER_ID, ORDER_DATE, CUSTOMER_ID, SHIP_DATE, TOTAL
  INTO R_ORDER
  FROM SALES_ORDER
  WHERE ORDER_ID = V_ORDEN_ID;

  DBMS_OUTPUT.PUT_LINE('ID: ' || R_ORDER.ORDER_ID);
  DBMS_OUTPUT.PUT_LINE('Fecha: ' || R_ORDER.ORDER_DATE);
  DBMS_OUTPUT.PUT_LINE('Customer ID: ' || R_ORDER.CUSTOMER_ID);
  DBMS_OUTPUT.PUT_LINE('Ship date: ' || R_ORDER.SHIP_DATE);
  DBMS_OUTPUT.PUT_LINE('Total: ' || R_ORDER.TOTAL);
EXCEPTION
  WHEN NO_DATA_FOUND THEN
    DBMS_OUTPUT.PUT_LINE('No se encontro el ID: ' || V_ORDEN_ID);
END;

