DECLARE
  V_DEPTO_ID DEPARTMENT.DEPARTMENT_ID%TYPE := &INGRESE_ID_DEPTO;
  V_NOMBRE_DEPTO DEPARTMENT.NAME%TYPE;
  V_CANT_EMPLEADOS INTEGER;
BEGIN
  SELECT D.NAME, COUNT(E.EMPLOYEE_ID)
  INTO V_NOMBRE_DEPTO, V_CANT_EMPLEADOS
  FROM DEPARTMENT D
  LEFT OUTER JOIN EMPLOYEE E
    ON D.DEPARTMENT_ID = E.DEPARTMENT_ID
  WHERE D.DEPARTMENT_ID = V_DEPTO_ID
  GROUP BY D.NAME;

  DBMS_OUTPUT.PUT_LINE('Departamento: ' || V_NOMBRE_DEPTO);
  CASE
    WHEN V_CANT_EMPLEADOS = 0 THEN
      DBMS_OUTPUT.PUT_LINE('Sin empleados');
    WHEN V_CANT_EMPLEADOS BETWEEN 1 AND 10 THEN
      DBMS_OUTPUT.PUT_LINE('Normal');
    ELSE
      DBMS_OUTPUT.PUT_LINE('Muchos');
  END CASE;
EXCEPTION
  WHEN NO_DATA_FOUND THEN
    DBMS_OUTPUT.PUT_LINE('No se encontró el departamento con ID: ' || V_DEPTO_ID);
  WHEN OTHERS THEN
    DBMS_OUTPUT.PUT_LINE('Error inesperado: ' || SQLERRM);
END;

