DECLARE
  V_PRODUCT_ID PRODUCT.PRODUCT_ID%TYPE := &INGRESE_PRODUCT_ID;
  V_DESCRIPCION PRODUCT.DESCRIPTION%TYPE;
  V_CANT_VENTAS INTEGER;
BEGIN
  SELECT P.DESCRIPTION, COUNT(I.ORDER_ID)
  INTO V_DESCRIPCION, V_CANT_VENTAS
  FROM PRODUCT P
  LEFT OUTER JOIN ITEM I
    ON P.PRODUCT_ID = I.PRODUCT_ID
  WHERE P.PRODUCT_ID = V_PRODUCT_ID
  GROUP BY (P.DESCRIPTION);

  DBMS_OUTPUT.PUT_LINE('Producto: ' || V_DESCRIPCION);
  DBMS_OUTPUT.PUT_LINE('Ventas: ' || V_CANT_VENTAS);
EXCEPTION
  WHEN NO_DATA_FOUND THEN
    DBMS_OUTPUT.PUT_LINE('No se encontró el producto con ID: ' || V_PRODUCT_ID);
  WHEN OTHERS THEN
    DBMS_OUTPUT.PUT_LINE('Error inesperado: ' || SQLERRM);
