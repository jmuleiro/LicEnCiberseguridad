DECLARE
  V_EMPLOYEE_ID EMPLOYEE.EMPLOYEE_ID%TYPE := &INGRESE_ID_EMPLEADO;
  TYPE TR_EMPLEADO IS RECORD (
    EMPLOYEE_ID EMPLOYEE.EMPLOYEE_ID%TYPE,
    EMPLOYEE_NAME VARCHAR2(250),
    MANAGER_ID EMPLOYEE.MANAGER_ID%TYPE,
    MANAGER_NAME VARCHAR2(250)
  );
  R_EMPLEADO TR_EMPLEADO;
BEGIN
  SELECT E1.EMPLOYEE_ID, 
    E1.FIRST_NAME || ' ' || E1.LAST_NAME,
    E1.MANAGER_ID,
    E2.FIRST_NAME || ' ' || E2.LAST_NAME
  INTO R_EMPLEADO
  FROM EMPLOYEE E1
  LEFT OUTER JOIN EMPLOYEE E2
    ON E1.MANAGER_ID = E2.EMPLOYEE_ID
  WHERE E1.EMPLOYEE_ID = V_EMPLOYEE_ID;

  DBMS_OUTPUT.PUT_LINE('ID: ' || R_EMPLEADO.EMPLOYEE_ID);
  DBMS_OUTPUT.PUT_LINE('Nombre: ' || R_EMPLEADO.EMPLOYEE_NAME);
  IF R_EMPLEADO.MANAGER_ID IS NOT NULL THEN
    DBMS_OUTPUT.PUT_LINE('ID Jefe: ' || R_EMPLEADO.MANAGER_ID);
    DBMS_OUTPUT.PUT_LINE('Nombre Jefe: ' || R_EMPLEADO.MANAGER_NAME);
  ELSE
    DBMS_OUTPUT.PUT_LINE('Jefe: No tiene');
  END IF;
EXCEPTION
  WHEN NO_DATA_FOUND THEN
    DBMS_OUTPUT.PUT_LINE('No se encontró el empleado con ID: ' || V_EMPLOYEE_ID);
  WHEN OTHERS THEN
    DBMS_OUTPUT.PUT_LINE('Error inesperado: ' || SQLERRM);
END;

