DECLARE
  V_ID_CLIENTE CUSTOMER.CUSTOMER_ID%TYPE := &INGRESE_SU_ID;
  V_CANT_ORDENES INTEGER := 0;
  V_CUSTOMER_NAME CUSTOMER.NAME%TYPE;
BEGIN
  SELECT COUNT(ORDER_ID)
  INTO V_CANT_ORDENES
  FROM SALES_ORDER
  WHERE CUSTOMER_ID = V_ID_CLIENTE;

  SELECT NAME
  INTO V_CUSTOMER_NAME
  FROM CUSTOMER
  WHERE CUSTOMER_ID = V_ID_CLIENTE;

  CASE 
    WHEN V_CANT_ORDENES < 3 THEN
      DBMS_OUTPUT.PUT_LINE('El cliente ' || V_CUSTOMER_NAME || ' ES REGULAR');
    WHEN V_CANT_ORDENES BETWEEN 4 AND 6 THEN
      DBMS_OUTPUT.PUT_LINE('El cliente ' || V_CUSTOMER_NAME || ' ES BUENO');
    ELSE
      DBMS_OUTPUT.PUT_LINE('El cliente ' || V_CUSTOMER_NAME || ' ES MUY BUENO');
  END CASE;
EXCEPTION
  WHEN NO_DATA_FOUND THEN
    DBMS_OUTPUT.PUT_LINE('No se encontraron órdenes sujetas al ID de cliente');
END;

