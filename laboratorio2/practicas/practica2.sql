DECLARE
  V_NUM_MULTIPLOS INTEGER := &INGRESE_NUMERO;
  V_MENSAJE VARCHAR2(100) := '';
  E_NUMERO_GRANDE EXCEPTION;
BEGIN
  IF V_NUM_MULTIPLOS > 10 THEN
    RAISE E_NUMERO_GRANDE;
  END IF;
  FOR I IN 1..V_NUM_MULTIPLOS LOOP
    IF I = V_NUM_MULTIPLOS THEN
      V_MENSAJE := V_MENSAJE || 3 * I;
      CONTINUE;
    END IF;
    V_MENSAJE := V_MENSAJE || 3 * I || ', ';
  END LOOP;
  DBMS_OUTPUT.PUT_LINE('Resultado: ' || V_MENSAJE);
EXCEPTION
  WHEN E_NUMERO_GRANDE THEN
    DBMS_OUTPUT.PUT_LINE('No se admiten más de 10 múltiplos.');
  WHEN OTHERS THEN
    DBMS_OUTPUT.PUT_LINE('Error inesperado: ' || SQLERRM);
END;
