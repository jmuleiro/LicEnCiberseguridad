DECLARE
  V_EMPLOYEE_ID EMPLOYEE.EMPLOYEE_ID%TYPE := &INGRESE_ID_EMPLEADO;
  V_RESULTADO INTEGER;
  V_MENSAJE VARCHAR2(100) := '';
  TYPE TR_EMPLEADO IS RECORD (
    APELLIDO EMPLOYEE.LAST_NAME%TYPE,
    NOMBRE EMPLOYEE.FIRST_NAME%TYPE,
    SALARIO EMPLOYEE.SALARY%TYPE
  );
  R_EMPLEADO TR_EMPLEADO;
BEGIN
  SELECT LAST_NAME, FIRST_NAME, SALARY
  INTO R_EMPLEADO
  FROM EMPLOYEE
  WHERE EMPLOYEE_ID = V_EMPLOYEE_ID;

  DBMS_OUTPUT.PUT_LINE(R_EMPLEADO.APELLIDO || ', ' || R_EMPLEADO.NOMBRE);
  V_RESULTADO := FLOOR(R_EMPLEADO.SALARIO / 100);
  FOR I IN 1..V_RESULTADO LOOP
    V_MENSAJE := V_MENSAJE || '*';
  END LOOP;
  DBMS_OUTPUT.PUT_LINE(V_MENSAJE);
EXCEPTION
  WHEN NO_DATA_FOUND THEN
    DBMS_OUTPUT.PUT_LINE('No se encontró empleado para el ID: ' || V_EMPLOYEE_ID);
  WHEN OTHERS THEN
    DBMS_OUTPUT.PUT_LINE('Error inesperado: ' || SQLERRM);
END;

