DECLARE
  CURSOR C_DEPTOS IS
    SELECT D.DEPARTMENT_ID, D.NAME, L.REGIONAL_GROUP
    FROM DEPARTMENT D, LOCATION L
    WHERE D.LOCATION_ID = L.LOCATION_ID
    ORDER BY DEPARTMENT_ID;
  CURSOR C_EMPLEADOS (P_DEP_ID DEPARTMENT.DEPARTMENT_ID%TYPE) IS
    SELECT FIRST_NAME, LAST_NAME, HIRE_DATE
    FROM EMPLOYEE
    WHERE DEPARTMENT_ID = P_DEP_ID
    ORDER BY LAST_NAME, FIRST_NAME;
BEGIN
  FOR DEPTO IN C_DEPTOS LOOP
    DBMS_OUTPUT.PUT_LINE(DEPTO.DEPARTMENT_ID || ' - ' || DEPTO.NAME || ' - ' || DEPTO.REGIONAL_GROUP);
    DBMS_OUTPUT.PUT_LINE('------------------------------');
    FOR EMPL IN C_EMPLEADOS(DEPTO.DEPARTMENT_ID) LOOP
      DBMS_OUTPUT.PUT_LINE(EMPL.LAST_NAME || ', ' || EMPL.FIRST_NAME || '     ' || EMPL.HIRE_DATE);
    END LOOP;
    DBMS_OUTPUT.PUT_LINE('');
  END LOOP;
END;
