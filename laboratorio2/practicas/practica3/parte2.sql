DECLARE
  CURSOR C_CURSOR IS
    SELECT S.ORDER_ID, S.ORDER_DATE, I.PRODUCT_ID
    FROM SALES_ORDER S, ITEM I
    WHERE S.ORDER_ID = I.ORDER_ID;
BEGIN
  FOR REC IN C_CURSOR LOOP
    DBMS_OUTPUT.PUT_LINE('ORDER_ID: ' || REC.ORDER_ID || ', DATE: ' || REC.ORDER_DATE || ', PRODUCT_ID: ' || REC.PRODUCT_ID);
  END LOOP;
END;

