DECLARE
  V_CUSTOMER_ID CUSTOMER.CUSTOMER_ID%TYPE := &INGRESE_CUSTOMER_ID;
  V_CONT INTEGER := 0;
  CURSOR C_ORDEN IS
    SELECT S.ORDER_ID, S.ORDER_DATE, P.DESCRIPTION
    FROM SALES_ORDER S, ITEM I, PRODUCT P
    WHERE S.CUSTOMER_ID = V_CUSTOMER_ID
      AND S.ORDER_ID = I.ORDER_ID
      AND I.PRODUCT_ID = P.PRODUCT_ID;
BEGIN
  FOR REC IN C_ORDEN LOOP
    V_CONT := V_CONT + 1;
    DBMS_OUTPUT.PUT_LINE('ORDER_ID: ' || REC.ORDER_ID || ', DATE: ' || REC.ORDER_DATE || ', DESCR: ' || REC.DESCRIPTION);
  END LOOP;

  IF V_CONT = 0 THEN
    DBMS_OUTPUT.PUT_LINE('No se encontraron registros');
  END IF;
END;

-- 10)
DECLARE
  V_DEPTO_ID DEPARTMENT.DEPARTMENT_ID%TYPE := &INGRESE_ID;
  V_CONT INTEGER := 0;
  CURSOR C_DEPTOS IS
    SELECT E.LAST_NAME, E.FIRST_NAME, E.SALARY
    FROM EMPLOYEE E, JOB J
    WHERE E.DEPARTMENT_ID = V_DEPTO_ID
    AND E.JOB_ID = J.JOB_ID
    AND J.FUNCTION = 'CLERK'
    ORDER BY E.LAST_NAME;
  E_NO_CLERKS EXCEPTION;
BEGIN
  FOR REC IN C_DEPTOS LOOP
    V_CONT := V_CONT + 1;
    CASE
      WHEN REC.SALARY < 1000 THEN
        DBMS_OUTPUT.PUT_LINE(REC.LAST_NAME || ', ' || REC.FIRST_NAME || ' es candidato a aumento');
      ELSE
        DBMS_OUTPUT.PUT_LINE(REC.LAST_NAME || ', ' || REC.FIRST_NAME || ' no es candidato a aumento');
    END CASE;
  END LOOP;

  IF V_CONT = 0 THEN
    RAISE E_NO_CLERKS;
  END IF;
EXCEPTION
  WHEN E_NO_CLERKS THEN
    DBMS_OUTPUT.PUT_LINE('El departamento ' || V_DEPTO_ID || ' no tiene candidatos a aumento de salario.');
END;

