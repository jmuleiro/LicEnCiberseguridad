DECLARE
  TYPE TR_EMPLOYEE IS RECORD (
    EMPLOYEE_ID EMPLOYEE.EMPLOYEE_ID%TYPE,
    SALARY EMPLOYEE.SALARY%TYPE,
    COMMISSION EMPLOYEE.COMMISSION%TYPE
  );
  R_EMPLOYEE TR_EMPLOYEE;
  V_CONT_NULO INTEGER := 0;
  V_CONT_10 INTEGER := 0;
  V_CONT_15 INTEGER := 0;
  V_CONT_20 INTEGER := 0;
BEGIN
  FOR R_EMPLOYEE IN (
    SELECT EMPLOYEE_ID, SALARY, COMMISSION
    FROM EMPLOYEE
  ) LOOP
    IF R_EMPLOYEE.COMMISSION IS NULL THEN
      V_CONT_NULO := V_CONT_NULO + 1;
      CONTINUE;
    END IF;

    CASE
      WHEN R_EMPLOYEE.SALARY < 1300 THEN
        UPDATE EMPLOYEE
        SET COMMISSION = COMMISSION * 1.10
        WHERE EMPLOYEE_ID = R_EMPLOYEE.EMPLOYEE_ID;
        V_CONT_10 := V_CONT_10 + 1;
      WHEN R_EMPLOYEE.SALARY BETWEEN 1300 AND 1500 THEN
        UPDATE EMPLOYEE
        SET COMMISSION = COMMISSION * 1.15
        WHERE EMPLOYEE_ID = R_EMPLOYEE.EMPLOYEE_ID;
        V_CONT_15 := V_CONT_15 + 1;
      ELSE
        UPDATE EMPLOYEE
        SET COMMISSION = COMMISSION * 1.20
        WHERE EMPLOYEE_ID = R_EMPLOYEE.EMPLOYEE_ID;
        V_CONT_20 := V_CONT_20 + 1;
    END CASE;
  END LOOP;

  DBMS_OUTPUT.PUT_LINE('Nulos: ' || V_CONT_NULO);
  DBMS_OUTPUT.PUT_LINE('10%: ' || V_CONT_10);
  DBMS_OUTPUT.PUT_LINE('15%: ' || V_CONT_15);
  DBMS_OUTPUT.PUT_LINE('20%: ' || V_CONT_20);
EXCEPTION
  WHEN OTHERS THEN
    DBMS_OUTPUT.PUT_LINE('Error inesperado: ' || SQLERRM);
END;

