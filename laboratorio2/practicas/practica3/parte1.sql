DECLARE
  V_EMPLOYEE_ID EMPLOYEE.EMPLOYEE_ID%TYPE := &INGRESE_ID_EMPLEADO;
  V_SALARY EMPLOYEE.SALARY%TYPE;
  V_COMMISSION EMPLOYEE.COMMISSION%TYPE;
  V_INCREMENTO BINARY_DOUBLE;
  E_COMISION_NULA EXCEPTION;
BEGIN
  SELECT SALARY, COMMISSION
  INTO V_SALARY, V_COMMISSION
  FROM EMPLOYEE
  WHERE EMPLOYEE_ID = V_EMPLOYEE_ID;

  IF V_COMMISSION IS NULL THEN
    RAISE E_COMISION_NULA;
  END IF;

  CASE
    WHEN V_SALARY < 1300 THEN
      V_INCREMENTO := 1.10;
    WHEN V_SALARY BETWEEN 1300 AND 1500 THEN
      V_INCREMENTO := 1.15;
    ELSE
      V_INCREMENTO := 1.20;
  END CASE;

  UPDATE EMPLOYEE
  SET COMMISSION = COMMISSION * V_INCREMENTO
  WHERE EMPLOYEE_ID = V_EMPLOYEE_ID;

  DBMS_OUTPUT.PUT_LINE('Comisión actualizada');

EXCEPTION
  WHEN NO_DATA_FOUND THEN
    DBMS_OUTPUT.PUT_LINE('No se encontró el empleado con ID: ' || V_EMPLOYEE_ID);
  WHEN E_COMISION_NULA THEN
    DBMS_OUTPUT.PUT_LINE('El empleado no tiene comisión');
  WHEN OTHERS THEN
    DBMS_OUTPUT.PUT_LINE('Error inesperado: ' || SQLERRM);
END;

