DECLARE
  V_PRODUCT_ID PRODUCT.PRODUCT_ID%TYPE := &INGRESE_PRODUCT_ID;
  V_PORCENTAJE INTEGER;
  TYPE TR_PRICE IS RECORD (
    PRODUCT_ID PRICE.PRODUCT_ID%TYPE,
    LIST_PRICE PRICE.LIST_PRICE%TYPE,
    MIN_PRICE PRICE.MIN_PRICE%TYPE,
    START_DATE PRICE.START_DATE%TYPE,
    VENTAS INTEGER
  );
  R_PRICE TR_PRICE;
BEGIN
  SELECT P.PRODUCT_ID, P.LIST_PRICE, P.MIN_PRICE, P.START_DATE, COUNT(I.ORDER_ID)
  INTO R_PRICE
  FROM PRICE P 
  LEFT OUTER JOIN ITEM I 
    ON P.PRODUCT_ID = I.PRODUCT_ID
  WHERE P.PRODUCT_ID = V_PRODUCT_ID AND
    P.END_DATE IS NULL
  GROUP BY P.PRODUCT_ID, P.LIST_PRICE, P.MIN_PRICE, P.START_DATE;

  CASE
    WHEN R_PRICE.VENTAS <= 2 THEN
      V_PORCENTAJE := 90;
    WHEN R_PRICE.VENTAS > 2 THEN
      V_PORCENTAJE := 80;
    ELSE
      V_PORCENTAJE := 50;
  END CASE;

  DBMS_OUTPUT.PUT_LINE('Reduciendo precio del producto con ID ' || V_PRODUCT_ID || ' al ' || V_PORCENTAJE || '%');

  UPDATE PRICE
  SET END_DATE = SYSDATE()
  WHERE PRODUCT_ID = R_PRICE.PRODUCT_ID
  AND END_DATE IS NULL;

  INSERT INTO PRICE (PRODUCT_ID, LIST_PRICE, MIN_PRICE, START_DATE, END_DATE)
  VALUES (
    R_PRICE.PRODUCT_ID, 
    (R_PRICE.LIST_PRICE * V_PORCENTAJE) / 100,
    (R_PRICE.MIN_PRICE * V_PORCENTAJE) / 100,
    SYSDATE(),
    NULL
  );
EXCEPTION
  WHEN NO_DATA_FOUND THEN
    DBMS_OUTPUT.PUT_LINE('No se encontró el producto con ID:' || V_PRODUCT_ID);
  WHEN OTHERS THEN
    DBMS_OUTPUT.PUT_LINE('Error inesperado: ' || SQLERRM);
END;

