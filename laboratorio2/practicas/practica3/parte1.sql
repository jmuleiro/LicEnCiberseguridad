DECLARE
  V_JOB_ID JOB.JOB_ID%TYPE;
  V_FUNCTION JOB.FUNCTION%TYPE := '&INGRESE_FUNCION';
BEGIN
  SELECT MAX(JOB_ID) + 1
  INTO V_JOB_ID
  FROM JOB;

  DBMS_OUTPUT.PUT_LINE('Insertando a JOB con ID ' || V_JOB_ID);

  INSERT INTO JOB (JOB_ID, FUNCTION)
  VALUES (V_JOB_ID, V_FUNCTION);
  COMMIT;
END;

