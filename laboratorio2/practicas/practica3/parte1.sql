DECLARE
  V_JOB_ID JOB.JOB_ID%TYPE := &INGRESE_JOB_ID;
  E_NOT_FOUND EXCEPTION;
  E_FK EXCEPTION;
  PRAGMA EXCEPTION_INIT(E_FK, -02292);
BEGIN
  DELETE FROM JOB
  WHERE JOB_ID = V_JOB_ID;

  IF SQL%NOTFOUND THEN
    RAISE E_NOT_FOUND;
  END IF;

EXCEPTION
  WHEN E_NOT_FOUND THEN
    DBMS_OUTPUT.PUT_LINE('No se encontró el Job con ID: ' || V_JOB_ID);
  WHEN E_FK THEN
    DBMS_OUTPUT.PUT_LINE('No se puede eliminar el Job con ID ' || V_JOB_ID || ' ya que hay empleados asignados al mismo.');
  WHEN OTHERS THEN
    DBMS_OUTPUT.PUT_LINE('Error inesperado: ' || SQLERRM);
END;

