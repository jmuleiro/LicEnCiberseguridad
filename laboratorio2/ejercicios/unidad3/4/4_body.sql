CREATE OR REPLACE PACKAGE BODY PA_PRODUCTOS AS

  E_NOT_FOUND EXCEPTION;
  E_INDEX_NOT_FOUND EXCEPTION;
  PRAGMA EXCEPTION_INIT(E_NOT_FOUND, -20001);
  PRAGMA EXCEPTION_INIT(E_INDEX_NOT_FOUND, -06502);

  TYPE TR_PRODUCT IS RECORD (
    PRODUCT_ID PRODUCT.PRODUCT_ID%TYPE,
    DESCR PRODUCT.DESCRIPTION%TYPE,
    CANTIDAD NUMBER
  );
  TYPE TT_PRODUCT IS TABLE OF TR_PRODUCT INDEX BY binary_integer;
  T_PRODUCT TT_PRODUCT;

  FUNCTION FU_PRODUCT_BY_DESCR(
    PI_DESCR IN PRODUCT.DESCRIPTION%TYPE
  ) RETURN PRODUCT.PRODUCT_ID%TYPE IS
    IDX NUMBER := T_PRODUCT.FIRST;
    V_FILA TR_PRODUCT;
    E_NOT_FOUND EXCEPTION;
  BEGIN
    LOOP
      V_FILA := T_PRODUCT(IDX);
      EXIT WHEN IDX = T_PRODUCT.LAST OR V_FILA.DESCR = PI_DESCR;
      IDX := T_PRODUCT.NEXT(IDX);
    END LOOP;

    IF V_FILA.DESCR = PI_DESCR THEN
      RETURN V_FILA.PRODUCT_ID;
    END IF;

    RAISE E_NOT_FOUND;
  EXCEPTION
    WHEN E_NOT_FOUND THEN
      RAISE_APPLICATION_ERROR(-20001, 'No se encontro el producto');
  END FU_PRODUCT_BY_DESCR;

  FUNCTION FU_GET_PRODUCT_IDX(
    PI_PRODUCT_ID IN PRODUCT.PRODUCT_ID%TYPE
  ) RETURN NUMBER IS
    IDX NUMBER;
  BEGIN
    IDX := T_PRODUCT.FIRST;
    WHILE T_PRODUCT(IDX).PRODUCT_ID != PI_PRODUCT_ID LOOP
      IDX := T_PRODUCT.NEXT(IDX);
    END LOOP;

    RETURN IDX;
  EXCEPTION
    WHEN NO_DATA_FOUND OR E_INDEX_NOT_FOUND THEN
      RAISE_APPLICATION_ERROR(-20001, 'No se encontro el producto con ID: ' || PI_PRODUCT_ID);
  END;

  PROCEDURE PR_BAJA(PI_ID PRODUCT.PRODUCT_ID%TYPE) AS
    e_fk exception;
    pragma exception_init (e_fk, -2292);
  BEGIN
    delete 
    from product 
    where PRODUCT_ID = PI_ID;
    if sql%rowcount = 0 then
      dbms_output.put_line('El producto con ID' || PI_ID || ' no existe');
    else   
      dbms_output.put_line('El producto se borro exitosamente');
    end if;   

  exception
    when e_fk then
      dbms_output.put_line('El producto tiene relaciones y no se puede borrar');
    WHEN OTHERS THEN
      DBMS_OUTPUT.PUT_LINE('Error desconocido al eliminar el producto: ' || SQLERRM);
  END PR_BAJA;

  PROCEDURE PR_BAJA(PI_DESCR PRODUCT.DESCRIPTION%TYPE) AS
    V_PRODUCT_ID PRODUCT.PRODUCT_ID%TYPE;
  BEGIN
    V_PRODUCT_ID := FU_PRODUCT_BY_DESCR(PI_DESCR);
    PR_BAJA(V_PRODUCT_ID);
  EXCEPTION
    WHEN E_NOT_FOUND THEN
      DBMS_OUTPUT.PUT_LINE('No se encontro el producto');
    WHEN OTHERS THEN
      DBMS_OUTPUT.PUT_LINE('Error desconocido al eliminar el producto: ' || SQLERRM);
  END PR_BAJA;

  PROCEDURE PR_LISTADO(PI_PRODUCT_ID IN PRODUCT.PRODUCT_ID%TYPE) AS
    CURSOR C_PRECIOS IS
      SELECT LIST_PRICE, MIN_PRICE, START_DATE, END_DATE
      FROM PRICE
      WHERE PRODUCT_ID = PI_PRODUCT_ID
      ORDER BY START_DATE;
    IDX NUMBER;
  BEGIN
    DBMS_OUTPUT.PUT_LINE('Product ID: ' || PI_PRODUCT_ID);
    FOR R_PRECIO IN C_PRECIOS LOOP
      DBMS_OUTPUT.PUT_LINE(' ' || R_PRECIO.LIST_PRICE || ' ' || R_PRECIO.MIN_PRICE || ' ' || R_PRECIO.START_DATE || ' ' || R_PRECIO.END_DATE);
    END LOOP;

    IDX := FU_GET_PRODUCT_IDX(PI_PRODUCT_ID);
    DBMS_OUTPUT.PUT_LINE('Cantidad vendida: ' || T_PRODUCT(IDX).CANTIDAD);
  EXCEPTION
    WHEN E_NOT_FOUND THEN
      DBMS_OUTPUT.PUT_LINE('No se encontro el producto con ID: ' || PI_PRODUCT_ID);
    WHEN OTHERS THEN
      DBMS_OUTPUT.PUT_LINE('Error desconocido: ' || SQLERRM);
  END PR_LISTADO;

  PROCEDURE PR_LISTADO(PI_PRODUCT_DESCR IN PRODUCT.DESCRIPTION%TYPE) AS
    V_PRODUCT_ID PRODUCT.PRODUCT_ID%TYPE;
  BEGIN
    V_PRODUCT_ID := FU_PRODUCT_BY_DESCR(PI_PRODUCT_DESCR);
    PR_LISTADO(V_PRODUCT_ID);
  EXCEPTION
    WHEN E_NOT_FOUND THEN
      DBMS_OUTPUT.PUT_LINE('No se encontro el producto con descripcion: ' || PI_PRODUCT_DESCR);
    WHEN OTHERS THEN
      DBMS_OUTPUT.PUT_LINE('Error desconocido: ' || SQLERRM);
  END PR_LISTADO;

  PROCEDURE PR_LISTADO AS
    IDX NUMBER;
  BEGIN
    IDX := T_PRODUCT.FIRST;
    LOOP
      PR_LISTADO(T_PRODUCT(IDX).PRODUCT_ID);
      DBMS_OUTPUT.PUT_LINE('---------------');
      EXIT WHEN IDX = T_PRODUCT.LAST;
      IDX := T_PRODUCT.NEXT(IDX);
    END LOOP;
  EXCEPTION
    WHEN OTHERS THEN
      DBMS_OUTPUT.PUT_LINE('Error desconocido: ' || SQLERRM);
  END PR_LISTADO;

--one-time only
BEGIN
  SELECT P.PRODUCT_ID, P.DESCRIPTION, SUM(NVL(I.QUANTITY, 0))
  BULK COLLECT INTO T_PRODUCT
  FROM PRODUCT P, ITEM I
  WHERE P.PRODUCT_ID = I.PRODUCT_ID (+)
  GROUP BY P.PRODUCT_ID, P.DESCRIPTION;
END PA_PRODUCTOS;
