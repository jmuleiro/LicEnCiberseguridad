CREATE OR REPLACE PACKAGE BODY PA_EMPLEADOS AS

  --* Excepciones
  E_MGR_NOT_FOUND EXCEPTION;
  E_FU_DEPT_ERROR EXCEPTION;
  E_FU_EMPL_ERROR EXCEPTION;
  E_DEPT_NOT_FOUND EXCEPTION;
  PRAGMA EXCEPTION_INIT(E_MGR_NOT_FOUND, -20001);
  PRAGMA EXCEPTION_INIT(E_FU_DEPT_ERROR, -20004);
  PRAGMA EXCEPTION_INIT(E_FU_EMPL_ERROR, -20005);
  PRAGMA EXCEPTION_INIT(E_DEPT_NOT_FOUND, -20002);

  --* Tablas
  TYPE TT_DEPT IS TABLE OF DEPARTMENT%ROWTYPE;
  T_DEPT TT_DEPT;

  --* Funciones
  FUNCTION FU_DEPT_ID (
    PI_DEPT_NAME DEPARTMENT.NAME%TYPE,
    PI_LOCATION_ID DEPARTMENT.LOCATION_ID%TYPE
  ) RETURN DEPARTMENT.DEPARTMENT_ID%TYPE IS
    IDX NUMBER := T_DEPT.FIRST;
    V_FILA DEPARTMENT%ROWTYPE;
  BEGIN
    LOOP
      V_FILA := T_DEPT(IDX);
      EXIT WHEN (V_FILA.NAME = PI_DEPT_NAME AND V_FILA.LOCATION_ID = PI_LOCATION_ID) OR IDX = T_DEPT.LAST;
      IDX := T_DEPT.NEXT(IDX);
    END LOOP;

    IF V_FILA.NAME = PI_DEPT_NAME AND V_FILA.LOCATION_ID = PI_LOCATION_ID THEN
      RETURN V_FILA.DEPARTMENT_ID;
    END IF;

    RAISE E_DEPT_NOT_FOUND;
  EXCEPTION
    WHEN OTHERS THEN
      RAISE_APPLICATION_ERROR(-20004, 'Error desconocido al buscar el departamento: ' || SQLERRM);
  END FU_DEPT_ID;

  FUNCTION FU_TABLE_HAS_DEPT_ID(
    PI_DEPT_ID IN DEPARTMENT.DEPARTMENT_ID%TYPE
  ) RETURN BOOLEAN IS 
    IDX NUMBER := T_DEPT.FIRST;
    V_FILA DEPARTMENT%ROWTYPE;
  BEGIN
    LOOP
      V_FILA := T_DEPT(IDX);
      EXIT WHEN V_FILA.DEPARTMENT_ID = PI_DEPT_ID;
      IDX := T_DEPT.NEXT(IDX);
    END LOOP;

    RETURN TRUE;
  EXCEPTION
    WHEN OTHERS THEN
      RETURN FALSE;
  END;

  FUNCTION FU_DEPT_NAME (
    PI_DEPT_ID IN DEPARTMENT.DEPARTMENT_ID%TYPE
  ) RETURN DEPARTMENT.NAME%TYPE IS
    IDX NUMBER := T_DEPT.FIRST;
    V_FILA DEPARTMENT%ROWTYPE;
  BEGIN
    LOOP
      V_FILA := T_DEPT(IDX);
      EXIT WHEN V_FILA.DEPARTMENT_ID = PI_DEPT_ID;
      IDX := T_DEPT.NEXT(IDX);
    END LOOP;

    RETURN V_FILA.NAME;
  EXCEPTION
    WHEN OTHERS THEN
      RAISE E_DEPT_NOT_FOUND;
  END FU_DEPT_NAME;

  FUNCTION FU_EMPLOYEE_ID (
    PI_NOMBRE EMPLOYEE.FIRST_NAME%TYPE,
    PI_APELLIDO EMPLOYEE.LAST_NAME%TYPE
  ) RETURN EMPLOYEE.EMPLOYEE_ID%TYPE IS
    V_EMPLOYEE_ID EMPLOYEE.EMPLOYEE_ID%TYPE;
  BEGIN
    SELECT EMPLOYEE_ID
    INTO V_EMPLOYEE_ID
    FROM EMPLOYEE
    WHERE FIRST_NAME = PI_NOMBRE
    AND LAST_NAME = PI_APELLIDO;

    RETURN V_EMPLOYEE_ID;
  EXCEPTION
    WHEN TOO_MANY_ROWS THEN
      RAISE_APPLICATION_ERROR(-20005, 'Demasiadas filas para el empleadO: ' || PI_NOMBRE || ' ' || PI_APELLIDO);
  END FU_EMPLOYEE_ID;

  --* Procedimientos
  PROCEDURE PR_ALTA(
    PI_ID IN EMPLOYEE.EMPLOYEE_ID%TYPE,
    PI_NOMBRE IN EMPLOYEE.FIRST_NAME%TYPE,
    PI_APELLIDO IN EMPLOYEE.LAST_NAME%TYPE,
    PI_SALARIO IN EMPLOYEE.SALARY%TYPE,
    PI_MANAGER_ID IN EMPLOYEE.MANAGER_ID%TYPE,
    PI_DEPT_ID IN EMPLOYEE.DEPARTMENT_ID%TYPE DEFAULT 10
  ) AS
    E_SALARY_EXCEEDS_MGR EXCEPTION;
    PRAGMA EXCEPTION_INIT(E_SALARY_EXCEEDS_MGR, -20003);
    V_MANAGER_SALARY EMPLOYEE.SALARY%TYPE;
    V_DEPT_ID_PLACEHOLDER DEPARTMENT.DEPARTMENT_ID%TYPE;
  BEGIN
    BEGIN
      SELECT SALARY
      INTO V_MANAGER_SALARY
      FROM EMPLOYEE
      WHERE EMPLOYEE_ID = PI_MANAGER_ID;
    EXCEPTION
      WHEN NO_DATA_FOUND THEN
        RAISE E_MGR_NOT_FOUND;
    END;

    IF PI_SALARIO > V_MANAGER_SALARY THEN
      RAISE E_SALARY_EXCEEDS_MGR;
    END IF;

    BEGIN
      SELECT DEPARTMENT_ID
      INTO V_DEPT_ID_PLACEHOLDER
      FROM DEPARTMENT
      WHERE DEPARTMENT_ID = PI_DEPT_ID;
    EXCEPTION
      WHEN NO_DATA_FOUND THEN
        RAISE E_DEPT_NOT_FOUND;
    END;

    INSERT INTO EMPLOYEE (
      EMPLOYEE_ID, 
      FIRST_NAME, 
      LAST_NAME, 
      MANAGER_ID, 
      HIRE_DATE, 
      SALARY, 
      DEPARTMENT_ID)
    VALUES (
      PI_ID,
      PI_NOMBRE,
      PI_APELLIDO,
      PI_MANAGER_ID,
      SYSDATE(),
      PI_SALARIO,
      PI_DEPT_ID
    );

    DBMS_OUTPUT.PUT_LINE('Empleado creado correctamente');

  EXCEPTION
    WHEN E_MGR_NOT_FOUND THEN
      DBMS_OUTPUT.PUT_LINE('No existe empleado o jefe con ID ' || PI_MANAGER_ID);
    WHEN E_DEPT_NOT_FOUND THEN
      DBMS_OUTPUT.PUT_LINE('No existe el departamento con ID ' || PI_DEPT_ID);
    WHEN E_SALARY_EXCEEDS_MGR THEN
      DBMS_OUTPUT.PUT_LINE('El salario (' || PI_SALARIO || ') excede al del manager (' || V_MANAGER_SALARY || ')');
    WHEN DUP_VAL_ON_INDEX THEN
      DBMS_OUTPUT.PUT_LINE('Ya existe un empleado con el ID ' || PI_ID);
    WHEN OTHERS THEN
      DBMS_OUTPUT.PUT_LINE('Error inesperado al dar de alta un empleado: ' || SQLERRM);
  END PR_ALTA;

  PROCEDURE PR_ALTA (
    PI_ID IN EMPLOYEE.EMPLOYEE_ID%TYPE,
    PI_NOMBRE IN EMPLOYEE.FIRST_NAME%TYPE,
    PI_APELLIDO IN EMPLOYEE.LAST_NAME%TYPE,
    PI_SALARIO IN EMPLOYEE.SALARY%TYPE,
    PI_MANAGER_NAME IN EMPLOYEE.FIRST_NAME%TYPE,
    PI_MANAGER_SURNAME IN EMPLOYEE.LAST_NAME%TYPE,
    PI_DEPT_ID IN EMPLOYEE.DEPARTMENT_ID%TYPE DEFAULT 10
  ) AS
    V_MANAGER_ID EMPLOYEE.EMPLOYEE_ID%TYPE;
  BEGIN
    V_MANAGER_ID := FU_EMPLOYEE_ID(PI_MANAGER_NAME, PI_MANAGER_SURNAME);

    PR_ALTA(
      PI_ID,
      PI_NOMBRE,
      PI_APELLIDO,
      PI_SALARIO,
      V_MANAGER_ID,
      PI_DEPT_ID
    );
  
  EXCEPTION
    WHEN E_FU_EMPL_ERROR THEN
      DBMS_OUTPUT.PUT_LINE('Error al buscar al manager: ' || SQLERRM);
    WHEN NO_DATA_FOUND THEN
      DBMS_OUTPUT.PUT_LINE('No existe el manager: ' || PI_MANAGER_NAME || ' ' || PI_MANAGER_SURNAME);
    WHEN OTHERS THEN
      DBMS_OUTPUT.PUT_LINE('Error inesperado al dar de alta un empleado: ' || SQLERRM);
  END PR_ALTA;

  PROCEDURE PR_LISTADO (
    PI_DEPT_ID IN DEPARTMENT.DEPARTMENT_ID%TYPE
  ) AS
    TYPE TR_EMPLOYEE IS RECORD (
      FIRST_NAME EMPLOYEE.FIRST_NAME%TYPE,
      LAST_NAME EMPLOYEE.LAST_NAME%TYPE,
      SALARY EMPLOYEE.SALARY%TYPE
    );
    TYPE TT_EMPLOYEE IS TABLE OF TR_EMPLOYEE INDEX BY BINARY_INTEGER;
    T_EMPLOYEE TT_EMPLOYEE;
    V_SALARIOS_SUMA EMPLOYEE.SALARY%TYPE := 0;
    V_CONT NUMBER := 0;
    IDX NUMBER := 1;
  BEGIN
    IF NOT FU_TABLE_HAS_DEPT_ID(PI_DEPT_ID) THEN
      RAISE E_DEPT_NOT_FOUND;
    END IF;

    DBMS_OUTPUT.PUT_LINE('Departamento ' || FU_DEPT_NAME(PI_DEPT_ID));
    DBMS_OUTPUT.PUT_LINE('Nombre        Apellido        Salario');

    SELECT FIRST_NAME,
      LAST_NAME,
      SALARY
    BULK COLLECT INTO T_EMPLOYEE
    FROM EMPLOYEE
    WHERE DEPARTMENT_ID = PI_DEPT_ID;

    LOOP
      DBMS_OUTPUT.PUT_LINE(T_EMPLOYEE(IDX).FIRST_NAME || '     ' || T_EMPLOYEE(IDX).LAST_NAME || '     ' || T_EMPLOYEE(IDX).SALARY);
      V_SALARIOS_SUMA := V_SALARIOS_SUMA + T_EMPLOYEE(IDX).SALARY;
      V_CONT := V_CONT + 1;
      EXIT WHEN IDX = T_EMPLOYEE.LAST;
      IDX := T_EMPLOYEE.NEXT(IDX);
    END LOOP;

    DBMS_OUTPUT.PUT_LINE('Promedio del salario: ' || V_SALARIOS_SUMA / V_CONT);

  EXCEPTION
    WHEN E_DEPT_NOT_FOUND THEN
      DBMS_OUTPUT.PUT_LINE('No se encontro el departamento con iD: ' || PI_DEPT_ID);
    WHEN OTHERS THEN
      DBMS_OUTPUT.PUT_LINE('Error inesperado al listar empleados: ' || SQLERRM);
  END PR_LISTADO;

  PROCEDURE PR_LISTADO (
    PI_NOMBRE DEPARTMENT.NAME%TYPE, 
    PI_LOCATION_ID DEPARTMENT.LOCATION_ID%TYPE
  ) AS
    V_DEPT_ID DEPARTMENT.DEPARTMENT_ID%TYPE;
  BEGIN
    V_DEPT_ID := FU_DEPT_ID(PI_NOMBRE, PI_LOCATION_ID);
    PR_LISTADO(V_DEPT_ID);
  EXCEPTION
    WHEN E_FU_DEPT_ERROR THEN
      DBMS_OUTPUT.PUT_LINE('No se pudo listar: ' || SQLERRM);
    WHEN OTHERS THEN
      DBMS_OUTPUT.PUT_LINE('Error inesperado al listar empleados: ' || SQLERRM);
  END PR_LISTADO;

  PROCEDURE PR_LISTADO AS
    IDX NUMBER := T_DEPT.FIRST;
  BEGIN
    LOOP
      PR_LISTADO(T_DEPT(IDX).DEPARTMENT_ID);
      EXIT WHEN IDX = T_DEPT.LAST;
      IDX := T_DEPT.NEXT(IDX);
    END LOOP;
  EXCEPTION
    WHEN OTHERS THEN
      DBMS_OUTPUT.PUT_LINE('Error inesperado al listar empleados: ' || SQLERRM);
  END PR_LISTADO;

  PROCEDURE PR_ACTUALIZAR_SALARIO (
    PI_EMPLOYEE_ID IN EMPLOYEE.EMPLOYEE_ID%TYPE,
    PI_SALARY IN EMPLOYEE.SALARY%TYPE,
    PO_SALIDA OUT STRING
  ) AS
    E_EMP_NOT_FOUND EXCEPTION;
    PRAGMA EXCEPTION_INIT(E_EMP_NOT_FOUND, -20006);
    V_MANAGER_ID EMPLOYEE.EMPLOYEE_ID%TYPE;
    V_MANAGER_SALARY EMPLOYEE.SALARY%TYPE;
  BEGIN
    BEGIN
      SELECT MANAGER_ID
      INTO V_MANAGER_ID
      FROM EMPLOYEE
      WHERE EMPLOYEE_ID = PI_EMPLOYEE_ID;
    EXCEPTION
      WHEN NO_DATA_FOUND THEN
        RAISE E_EMP_NOT_FOUND;
    END;

    BEGIN
      SELECT SALARY
      INTO V_MANAGER_SALARY
      FROM EMPLOYEE
      WHERE EMPLOYEE_ID = V_MANAGER_ID;
    EXCEPTION
      WHEN NO_DATA_FOUND THEN
        RAISE E_MGR_NOT_FOUND;
    END;

    IF PI_SALARY < V_MANAGER_SALARY THEN
      PO_SALIDA := 'menor';
    ELSIF PI_SALARY > V_MANAGER_SALARY THEN
      PO_SALIDA := 'mayor';
    ELSE
      PO_SALIDA := 'igual';
    END IF;

    UPDATE EMPLOYEE
    SET SALARY = PI_SALARY
    WHERE EMPLOYEE_ID = PI_EMPLOYEE_ID;

    DBMS_OUTPUT.PUT_LINE('Salario actualizado correctamente');

  EXCEPTION
    WHEN E_EMP_NOT_FOUND THEN
      DBMS_OUTPUT.PUT_LINE('El empleado con ID ' || PI_EMPLOYEE_ID || ' no existe');
    WHEN E_MGR_NOT_FOUND THEN
      DBMS_OUTPUT.PUT_LINE('El empleado con ID ' || PI_EMPLOYEE_ID || ' no tiene manager');
    WHEN OTHERS THEN
      DBMS_OUTPUT.PUT_LINE('Error inesperado al actualizar salario: ' || SQLERRM);
  END PR_ACTUALIZAR_SALARIO;
  
--ONE-TIME-ONLY
BEGIN
  SELECT DEPARTMENT_ID, NAME, LOCATION_ID
  BULK COLLECT INTO T_DEPT
  FROM DEPARTMENT;
END PA_EMPLEADOS;